/**
 * Tool detail page, a generated micro-site for every live tool. All content
 * (hero, workspace, how-to, features, benefits, formats, FAQ, related tools and
 * articles, CTA) is derived from the single registry entry, so a tool is fully
 * live the moment its config object exists. The interactive workspace is a
 * client component code-split per tool and mounted client-side only.
 */

export const dynamicParams = false;

/**
 * Distil a tool's own copy into an answer-first, ~40–60 word snippet for the
 * AI-answer callout + speakable schema. Takes whole sentences up to a soft word
 * cap so the text reads naturally (never mid-sentence), then guarantees it ends
 * on a period. Pure/deterministic, derived only from existing config text.
 */
function buildAiAnswer(source: string): string {
  const text = source.replace(/\s+/g, " ").trim();
  const sentences = text.match(/[^.!?]+[.!?]+/g) ?? [text];
  const words = (s: string) => s.trim().split(/\s+/).filter(Boolean).length;

  let out = "";
  let count = 0;
  for (const sentence of sentences) {
    const next = count + words(sentence);
    if (out && next > 60) break;
    out = `${out} ${sentence}`.trim();
    count = next;
    if (count >= 40) break;
  }
  if (!out) out = text;
  return /[.!?]$/.test(out) ? out : `${out}.`;
}

interface ToolPageProps {
  params: Promise<{ tool: string }>;
}

/** Prerender a route for every live tool (skips beta / coming-soon entries). */
export function generateStaticParams(): { tool: string }[] {
  return getAllTools()
    .filter((tool) => tool.status === "live")
    .map((tool) => ({ tool: tool.slug }));
}

export async function generateMetadata({
  params,
}: ToolPageProps): Promise<Metadata> {
  const { tool: slug } = await params;
  const tool = getToolBySlug(slug);
  if (!tool) return {};

  const metadata = buildToolMetadata(tool);

  // The per-tool OG/Twitter image is generated by ./opengraph-image.tsx (Next's
  // file convention, rendered to a static PNG at build). Drop buildMetadata's
  // explicit images so that unique per-tool card is injected as both og:image
  // and twitter:image, instead of the shared per-category card.
  const openGraph = metadata.openGraph ? { ...metadata.openGraph } : undefined;
  const twitter = metadata.twitter
    ? { ...metadata.twitter, card: "summary_large_image" as const }
    : undefined;
  if (openGraph) delete openGraph.images;
  if (twitter) delete twitter.images;
  return { ...metadata, openGraph, twitter };
}

