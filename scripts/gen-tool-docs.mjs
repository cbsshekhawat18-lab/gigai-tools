/**
 * Writes the tool reference in docs/tools/ from the registry, so the docs list
 * exactly the tools the site ships. Run: npm run docs:tools
 *
 * Where a tool runs is read from its own source (modules/tools/<cat>/<slug>-tool.tsx):
 * a tool that imports one of the server helpers below uses the backend or a fetch
 * proxy for that part. Everything else runs only in the browser. CI regenerates
 * these files and fails if they differ from what is committed.
 *
 * The pages link each tool to its page on gigai.tools for the step-by-step guide,
 * rather than copying that text here.
 */
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createJiti } from "jiti";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const jiti = createJiti(join(root, "scripts", "gen-tool-docs.mjs"), { alias: { "@": root } });
const { TOOLS } = jiti(join(root, "config", "tools", "index.ts"));
const { CATEGORIES } = jiti(join(root, "config", "categories.ts"));

const SITE = "https://gigai.tools";
const OUT = join(root, "docs", "tools");

/**
 * Server helpers, and what using each one means for the visitor's data.
 * kind: "backend" = part of the tool runs on the backend; "proxy" = a URL you
 * enter is fetched by the site's proxy; "option" = off unless a site enables it.
 */
const SERVER_USES = [
  { kind: "backend", re: /lib\/video-work\/(analyze|ingest)/, note: "Analysis, and fetching a video link, run on the backend. Transcription and screenshots stay in the browser." },
  { kind: "backend", re: /iconlab\/ai-provider/, note: "The optional AI composer runs on the backend. Building and exporting icons stays in the browser." },
  { kind: "backend", re: /document-tools\/repair-client/, note: "Optional OCR repair sends the PDF to the backend, after a notice. Everything else stays in the browser." },
  { kind: "option", re: /convertOnServer/, note: "Converts in the browser. A self-hosted site whose backend has LibreOffice can turn on server conversion (NEXT_PUBLIC_SERVER_CONVERT); gigai.tools does not." },
  { kind: "proxy", re: /proxyFetchText|seo-tools\/fetch-url|PasteAnalyze|UrlPrefillBar|INSPECTOR_PROXY/, note: "" },
];
const LABEL = { backend: "Browser and backend", proxy: "Browser, URL via proxy", option: "Browser" };

/** slug -> module path, from the same registry the site uses to load each tool. */
const MODULES = new Map(
  [...readFileSync(join(root, "components", "tool", "tool-ui-registry.ts"), "utf8")
    .matchAll(/"([a-z0-9-]+)":\s*dynamic\(\(\) => import\("@\/(modules\/tools\/[^"]+)"\)/g)]
    .map((m) => [m[1], join(root, `${m[2]}.tsx`)]),
);

function runsOf(tool) {
  const file = MODULES.get(tool.slug);
  if (!file || !existsSync(file)) throw new Error(`gen-tool-docs: no interface module for live tool "${tool.slug}"`);
  const src = readFileSync(file, "utf8");
  const uses = SERVER_USES.filter((u) => u.re.test(src));
  const kind = ["backend", "proxy", "option"].find((k) => uses.some((u) => u.kind === k));
  return { label: kind ? LABEL[kind] : "Browser", kind, notes: uses.map((u) => u.note).filter(Boolean) };
}

const cell = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
const formats = (list) => (list && list.length ? list.join(", ") : "");

const live = TOOLS.filter((t) => (t.status ?? "live") === "live");
const categories = CATEGORIES.map((c) => ({ ...c, tools: live.filter((t) => t.category === c.slug) })).filter((c) => c.tools.length);

if (existsSync(OUT)) rmSync(OUT, { recursive: true });
mkdirSync(OUT, { recursive: true });

const header = "<!-- Generated by scripts/gen-tool-docs.mjs from config/tools/. Do not edit by hand. -->\n";

for (const c of categories) {
  const rows = c.tools
    .slice()
    .sort((a, b) => a.title.localeCompare(b.title))
    .map((t) => ({ t, runs: runsOf(t) }));
  const withNotes = rows.filter((r) => r.runs.notes.length);
  const lines = [
    "---",
    `description: ${JSON.stringify(`All ${c.tools.length} tools in GigAI Tools' ${c.name}: what each one does, the files it takes and makes, and whether it runs in your browser.`)}`,
    "---",
    header,
    `# ${c.name}`,
    "",
    cell(c.description),
    "",
    `${c.tools.length} tools. Each name opens the tool on gigai.tools, where its page explains how to use it step by step.`,
    "",
    "| Tool | What it does | Input | Output | Runs |",
    "|---|---|---|---|---|",
    ...rows.map(({ t, runs }) =>
      `| [${cell(t.title)}](${SITE}/${t.slug}) | ${cell(t.tagline || t.description)} | ${cell(formats(t.formats?.input))} | ${cell(formats(t.formats?.output))} | ${runs.label} |`),
    "",
  ];
  if (withNotes.length) {
    lines.push("## Where the backend comes in", "");
    for (const { t, runs } of withNotes) lines.push(`- **${cell(t.title)}**: ${runs.notes.join(" ")}`);
    lines.push("");
  }
  if (rows.some((r) => r.runs.kind === "proxy")) {
    lines.push("## Tools that can read a URL", "",
      "The tools marked *Browser, URL via proxy* analyse HTML you paste, entirely in your browser. If you enter a URL instead, the site's fetch proxy retrieves the page, returns it and keeps nothing. See [What runs where](../privacy-model.md).", "");
  }
  writeFileSync(join(OUT, `${c.slug}.md`), lines.join("\n"));
}

const total = live.length;
const index = [
  "---",
  `description: ${JSON.stringify(`The complete list of GigAI Tools: ${total} free tools in ${categories.length} categories, grouped by what they work on, with where each one runs.`)}`,
  "---",
  header,
  "# All tools",
  "",
  `GigAI Tools has ${total} live tools in ${categories.length} categories. Each category page lists every tool with what it does, the files it takes and makes, and where it runs. Each tool name opens the tool on gigai.tools.`,
  "",
  "| Category | Tools | What they work on |",
  "|---|---|---|",
  ...categories.map((c) => `| [${cell(c.name)}](${c.slug}.md) | ${c.tools.length} | ${cell(c.description)} |`),
  "",
  "**Runs** means where your data is processed:",
  "",
  "- *Browser*: on your device only. Nothing is uploaded.",
  "- *Browser, URL via proxy*: pasted content stays on your device; a URL you enter is fetched by the site's proxy.",
  "- *Browser and backend*: one part of the tool uses the backend, as the category page explains.",
  "",
].join("\n");
writeFileSync(join(OUT, "index.md"), index);

console.log(`gen-tool-docs: ${total} tools in ${categories.length} categories -> docs/tools/`);
