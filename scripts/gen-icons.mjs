import fs from "node:fs";
import path from "node:path";
const lucide = await import("lucide-react");
const valid = new Set(Object.keys(lucide.icons));
console.log("lucide total icons:", valid.size);

const roots = ["config", "components", "modules", "lib", "app"];
const files = [];
function walk(d) {
  if (!fs.existsSync(d)) return;
  for (const e of fs.readdirSync(d)) {
    const p = path.join(d, e);
    let s;
    try { s = fs.statSync(p); } catch { continue; }
    if (s.isDirectory()) walk(p);
    else if (/\.(ts|tsx)$/.test(e) && !p.endsWith("icons.generated.ts")) files.push(p);
  }
}
for (const r of roots) walk(r);
console.log("scanned files:", files.length);

const used = new Set();
const re = /['"]([A-Z][A-Za-z0-9]+)['"]/g;
for (const f of files) {
  const t = fs.readFileSync(f, "utf8");
  let m;
  while ((m = re.exec(t))) if (valid.has(m[1])) used.add(m[1]);
}
used.add("Wrench");
const names = [...used].sort();
console.log("used icons found:", names.length, "(" + Math.round(names.length / valid.size * 100) + "% of lucide)");

const body = `// AUTO-GENERATED by scripts/gen-icons.mjs — do not edit by hand.
// A static map of ONLY the lucide icons this app references, so tree-shaking can
// drop the other ~${valid.size - names.length}. Regenerate after adding new icon
// names anywhere in config/components:   node scripts/gen-icons.mjs
import {
${names.map((n) => "  " + n + ",").join("\n")}
} from "lucide-react";
import type { ComponentType } from "react";
import type { LucideProps } from "lucide-react";

export type LucideIcon = ComponentType<LucideProps>;

/** Name -> component. O(1), tree-shakeable (only these icons are bundled). */
export const ICON_MAP: Record<string, LucideIcon> = {
${names.map((n) => "  " + n + ",").join("\n")}
};
`;
fs.writeFileSync("lib/icons.generated.ts", body);
fs.mkdirSync("scripts", { recursive: true });
fs.copyFileSync(new URL(import.meta.url), "scripts/gen-icons.mjs");
console.log("WROTE lib/icons.generated.ts with", names.length, "icons");

const missing = new Set();
for (const f of files) {
  const t = fs.readFileSync(f, "utf8");
  for (const m of t.matchAll(/(?:name|icon)\s*[:=]\s*["']([A-Z][A-Za-z0-9]+)["']/g)) {
    if (valid.has(m[1]) && !used.has(m[1])) missing.add(m[1]);
  }
}
console.log("literal icon refs NOT in map (should be 0):", missing.size, [...missing].slice(0, 20).join(" "));
