"""Model-assisted signal extraction for GigAI Verify.

WHAT THE MODEL IS AND IS NOT ALLOWED TO DO
------------------------------------------
The model never returns a verdict. It returns *observations*: named stylistic
patterns, each carrying verbatim quotes from the submitted text. Those
observations are converted into ordinary signals and fed through exactly the
same ``fusion.fuse()`` as the heuristics. The verdict is arithmetic, not opinion.

This matters because a language model asked "is this AI-written?" will answer
confidently either way — the question is one it cannot actually settle, and its
fluency makes a guess indistinguishable from a finding. Restricting it to
"point at what you see, and quote it" keeps it doing something it is genuinely
good at (noticing patterns in prose) and out of the part it is not.

THE HALLUCINATION GUARD
-----------------------
``_verify_quotes`` drops any observation whose quotes do not appear verbatim in
the submitted text. This is a mechanical check, not a prompt instruction, so it
holds regardless of how the model behaves. An observation that survives is one
whose evidence the user can find in their own content.

Model signals are also capped (``_STRENGTH_WEIGHT``) and are deliberately absent
from ``fusion.HARD_EVIDENCE_SIGNALS`` — so the model can contribute to a verdict
but can never, on its own, push a result to "high confidence".

PRIVACY: receive → analyse → respond → forget. The submitted text is held in
memory for one request and discarded with the response. It is never written to
disk or logged, and no content appears in any error path.
"""

from __future__ import annotations

import json
import logging
import re
from typing import Any, Final

from app.core.config import settings
from app.schemas.verify import (
    Classification,
    EvidenceItem,
    EvidenceKind,
    Signal,
    SignalDirection,
    SignalFamily,
    SignalReliability,
    SignalStrength,
)

logger = logging.getLogger("app.services.verify.llm")

#: Text sent to the model in one pass. Beyond this the caller samples first.
MAX_MODEL_CHARS: Final[int] = 24_000

#: Ceiling on how much a model observation can weigh. Below every hard-evidence
#: signal by design: the model is a second opinion, not a witness of record.
_STRENGTH_WEIGHT: Final[dict[str, float]] = {"low": 0.2, "medium": 0.35, "high": 0.55}

_ALLOWED_FAMILIES: Final[frozenset[str]] = frozenset({"stylometry", "structure"})

_SYSTEM_PROMPT: Final[str] = """\
You are the analysis stage of GigAI Verify, a tool that reports evidence about \
whether text was written by a person or generated by an AI model.

Your job is NARROW and you must not exceed it:

- You DO report specific, observable patterns in the text, each supported by \
short verbatim quotes copied exactly from the text you were given.
- You DO NOT decide whether the text is AI-generated. A separate deterministic \
stage weighs your observations against others. Never state or imply a verdict.
- You DO NOT estimate percentages, probabilities or scores of any kind.

Rules that will cause your output to be discarded if broken:

1. Every quote must appear EXACTLY in the supplied text, character for \
character. Do not paraphrase, correct, normalise or trim mid-word. Quotes are \
checked mechanically against the source.
2. Report only what is present. If the text shows no notable pattern, return an \
empty list. An empty list is a correct and useful answer.
3. Judge the text on its own terms. Formal or non-native English is not \
evidence of AI. Typos are not proof of humanity. Subject matter is irrelevant — \
an article about AI is not thereby AI-written.
4. Do not repeat an observation that is already covered by another; each entry \
must stand on a distinct pattern.

For each observation set `direction`:
  "ai"      - the pattern is more typical of generated text
  "human"   - the pattern is more typical of a person writing
  "neutral" - notable but not evidence either way

and `strength`: "low", "medium" or "high" — how distinctive the pattern is in \
THIS text, not how confident you feel overall.
"""

_OBSERVATION_SCHEMA: Final[dict[str, Any]] = {
    "type": "object",
    "properties": {
        "observations": {
            "type": "array",
            "description": (
                "Distinct observable patterns in the text. Empty if none are notable."
            ),
            "items": {
                "type": "object",
                "properties": {
                    "label": {
                        "type": "string",
                        "description": (
                            "Short user-facing name for the pattern, e.g. "
                            "'Repetitive paragraph openings'. Max 8 words. No verdict."
                        ),
                    },
                    "detail": {
                        "type": "string",
                        "description": (
                            "One or two sentences describing what was observed and why "
                            "it is notable. Plain language. State the observation, not a "
                            "conclusion about authorship."
                        ),
                    },
                    "direction": {"type": "string", "enum": ["ai", "human", "neutral"]},
                    "strength": {"type": "string", "enum": ["low", "medium", "high"]},
                    "family": {
                        "type": "string",
                        "enum": ["stylometry", "structure"],
                        "description": (
                            "'stylometry' for word- and sentence-level patterns; "
                            "'structure' for document shape and organisation."
                        ),
                    },
                    "quotes": {
                        "type": "array",
                        "description": (
                            "1-3 short excerpts copied EXACTLY from the supplied text "
                            "that demonstrate this pattern. Under 200 characters each."
                        ),
                        "items": {"type": "string"},
                    },
                },
                "required": ["label", "detail", "direction", "strength", "family", "quotes"],
                "additionalProperties": False,
            },
        }
    },
    "required": ["observations"],
    "additionalProperties": False,
}

_ASK_SYSTEM_PROMPT: Final[str] = """\
You are answering a follow-up question inside GigAI Verify.

You are given: the reading that was reached, and the complete list of signals \
that produced it. That list is ALL the evidence that exists. You cannot see the \
original content.

You may also be given REFERENCE MATERIAL describing what these KINDS of evidence \
generally mean. That material is background knowledge, NOT observations about \
this content. Use it to explain and qualify the findings — never to add one. If \
the reference material discusses a kind of evidence that does not appear in the \
signal list, that evidence was NOT found here and you must not imply otherwise.

Rules:

1. Answer only from the supplied signals. Never invent evidence, never refer to \
anything not in the list, and never re-analyse content you cannot see.
2. If the signals do not answer the question, say so plainly and state what they \
do establish. That is a good answer, not a failure.
3. Never give a percentage, score or probability.
4. Never claim certainty. These signals are evidence, not proof of authorship, \
and they produce both false positives and false negatives. If the user asks what \
you can prove, the honest answer is that inference from writing style proves \
nothing about a specific author.
5. Be brief and concrete — a short paragraph, or a few bullets. No preamble.
6. Cite the `id` of every signal your answer relies on in `cited_signal_ids`. \
Use ids exactly as given. Cite nothing if you relied on nothing.
"""

_ASK_SCHEMA: Final[dict[str, Any]] = {
    "type": "object",
    "properties": {
        "answer": {
            "type": "string",
            "description": "The reply shown to the user. Grounded in the supplied signals only.",
        },
        "cited_signal_ids": {
            "type": "array",
            "description": "Ids of signals the answer relies on. Empty if none.",
            "items": {"type": "string"},
        },
    },
    "required": ["answer", "cited_signal_ids"],
    "additionalProperties": False,
}


# ── Availability ──────────────────────────────────────────────────────────────


def active_provider() -> str:
    """Which hosted backend will serve an analysis: "anthropic" or ""."""
    return "anthropic" if settings.anthropic_api_key else ""


def model_available() -> bool:
    return bool(active_provider())


def active_model() -> str | None:
    return settings.verify_model if model_available() else None


# ── Anthropic plumbing ────────────────────────────────────────────────────────


def _client() -> Any:
    import anthropic

    return anthropic.Anthropic(api_key=settings.anthropic_api_key, timeout=90.0)


def _structured(
    system: str, user: str, schema: dict[str, Any], max_tokens: int
) -> dict[str, Any] | None:
    """One structured call. Returns None on any failure — never raises upward.

    Every caller has a working heuristic result already, so a model failure
    degrades the analysis instead of losing it.
    """
    try:
        message = _client().messages.create(
            model=settings.verify_model,
            max_tokens=max_tokens,
            system=system,
            messages=[{"role": "user", "content": user}],
            output_config={"format": {"type": "json_schema", "schema": schema}},
        )
    except Exception:  # noqa: BLE001 - degrade, and never log request content
        logger.exception("verify: model call failed")
        return None

    parsed = getattr(message, "parsed_output", None)
    if isinstance(parsed, dict):
        return parsed

    for block in message.content:
        if getattr(block, "type", None) == "text":
            try:
                loaded = json.loads(block.text)
            except json.JSONDecodeError:
                continue
            if isinstance(loaded, dict):
                return loaded

    return None


# ── Quote verification ────────────────────────────────────────────────────────


def _normalise(value: str) -> str:
    """Collapse whitespace and unify quote characters for comparison.

    Deliberately forgiving about typography (a model may straighten a curly
    apostrophe) and strict about everything else — the words must be the
    author's, in the author's order.
    """
    value = value.replace("’", "'").replace("‘", "'")
    value = value.replace("“", '"').replace("”", '"')
    value = value.replace("—", "-").replace("–", "-")
    return re.sub(r"\s+", " ", value).strip().lower()


def _verify_quotes(quotes: list[str], haystack: str) -> list[str]:
    """Keep only quotes that genuinely appear in the submitted text."""
    normalised_haystack = _normalise(haystack)
    kept: list[str] = []
    for quote in quotes:
        candidate = quote.strip()
        # Too short to be evidence of anything; a three-word match is noise.
        if len(candidate) < 12:
            continue
        if _normalise(candidate) in normalised_haystack:
            kept.append(candidate[:300])
    return kept


# ── Public API ────────────────────────────────────────────────────────────────


def extract_signals(text: str) -> list[Signal]:
    """Ask the model for observations and convert the survivors into signals.

    Returns an empty list when the model is unconfigured, fails, or produces
    nothing that passes the quote check.
    """
    if not model_available() or len(text.strip()) < 400:
        return []

    excerpt = text[:MAX_MODEL_CHARS]
    payload = _structured(
        _SYSTEM_PROMPT,
        f"Analyse the following text and report your observations.\n\n<text>\n{excerpt}\n</text>",
        _OBSERVATION_SCHEMA,
        max_tokens=4_000,
    )
    if not payload:
        return []

    raw = payload.get("observations")
    if not isinstance(raw, list):
        return []

    signals: list[Signal] = []
    for index, item in enumerate(raw[:10]):
        if not isinstance(item, dict):
            continue

        direction = str(item.get("direction", "neutral"))
        family = str(item.get("family", "stylometry"))
        strength = str(item.get("strength", "low"))
        label = str(item.get("label", "")).strip()
        detail = str(item.get("detail", "")).strip()

        if direction not in {"ai", "human", "neutral"} or family not in _ALLOWED_FAMILIES:
            continue
        if not label or not detail:
            continue

        quotes = item.get("quotes")
        verified = _verify_quotes(quotes, excerpt) if isinstance(quotes, list) else []

        # The guard: no verifiable quote, no signal. A neutral observation is
        # allowed through without one, since it carries no weight either way.
        if not verified and direction != "neutral":
            logger.info("verify: dropped an observation with no verifiable quote")
            continue

        signals.append(
            Signal(
                # The `llm.` prefix is load-bearing: it keeps these out of the
                # hard-evidence test in fusion.py, so a model observation can
                # contribute to a reading but never reach HIGH confidence alone.
                id=f"llm.observation-{index + 1}",
                family=SignalFamily.STYLOMETRY
                if family == "stylometry"
                else SignalFamily.STRUCTURE,
                label=label[:160],
                detail=detail[:800],
                direction=SignalDirection.AI
                if direction == "ai"
                else SignalDirection.HUMAN
                if direction == "human"
                else SignalDirection.NEUTRAL,
                strength=SignalStrength(strength) if strength in {"weak", "moderate", "strong"} else SignalStrength.WEAK,
                # A model reading prose is a stylometric method and is rated as
                # one, however fluent its explanation sounds.
                reliability=SignalReliability.LOW,
                # All model observations share one line of evidence: they come
                # from a single reading by a single model and would fail together.
                independence_group="llm-observations",
                alternative_explanations=[
                    "This is a model's reading of writing style, which is weak evidence of "
                    "authorship: careful human writing and edited AI drafts look alike.",
                    "Formal registers and non-native English trip the same impressions.",
                ],
                weight=0.0 if direction == "neutral" else _STRENGTH_WEIGHT.get(strength, 0.2),
                detector_id="llm.observations",
                detector_version="2.0.0",
                evidence=[
                    EvidenceItem(kind=EvidenceKind.EXCERPT, label="Quoted from the content", value=quote)
                    for quote in verified[:3]
                ],
            )
        )

    return signals


def answer(
    question: str,
    signals: list[Signal],
    classification: Classification,
    reference: str = "",
) -> tuple[str, list[str]] | None:
    """Answer a follow-up strictly from the supplied signals.

    ``reference`` is knowledge-base material about what these kinds of evidence
    mean, retrieved from the signals that were actually found (see
    ``knowledge.retrieve``). It is passed in a clearly-labelled block so the
    model can explain a finding without being able to mistake background for
    observation.

    Returns ``(answer, cited_ids)``, or None when the model is unavailable — the
    caller then falls back to a deterministic reply.
    """
    if not model_available():
        return None

    evidence = [
        {
            "id": signal.id,
            "title": signal.label,
            "finding": signal.detail,
            "direction": signal.direction.value,
            "category": signal.family.value,
            "reliability": signal.reliability.value,
            "alternativeExplanations": signal.alternative_explanations,
            "evidence": [
                {"kind": item.kind.value, "label": item.label, "value": item.value}
                for item in signal.evidence
            ],
        }
        for signal in signals
    ]

    payload = _structured(
        _ASK_SYSTEM_PROMPT,
        (
            f"Reading reached: {classification.value}\n\n"
            f"Signals (this is the complete evidence):\n{json.dumps(evidence, indent=2)}\n\n"
            f"{reference}\n"
            f"User's question: {question}"
        ),
        _ASK_SCHEMA,
        max_tokens=1_500,
    )
    if not payload:
        return None

    text = str(payload.get("answer", "")).strip()
    if not text:
        return None

    known = {signal.id for signal in signals}
    cited = payload.get("cited_signal_ids")
    # Drop invented ids rather than showing the user a citation to nothing.
    valid = [str(i) for i in cited if str(i) in known] if isinstance(cited, list) else []

    return text, valid
