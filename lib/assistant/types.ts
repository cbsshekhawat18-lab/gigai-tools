import type { BlogPost, IconName } from "@/types";

/**
 * GigAI Assistant, shared types for the LOCAL intent engine.
 *
 * The assistant is NOT a chatbot and NOT an LLM. It is a deterministic,
 * rules-based "product expert": synonyms + problem→tool mappings over the REAL
 * registry + discovery data. Every slug it returns is validated against the
 * registry, so it can never surface a tool/page that does not exist.
 *
 * Pure data. No React, no network. This module (and the rest of lib/assistant)
 * imports the registry, so the UI MUST lazy-load it on first interaction, the
 * same way the search bar lazy-loads lib/search today.
 */

/* ── Intent map (curated rules) ───────────────────────────────────────────── */

/**
 * A single curated rule: a set of natural-language PATTERNS (problems, tasks,
 * synonyms, abbreviations, plurals, all lower-case) mapped to a primary tool,
 * with optional related tools, a guided workflow and an "expert" note.
 */
export interface IntentRule {
  /** Lower-case keywords/phrases that trigger this rule (problems + synonyms). */
  patterns: string[];
  /** Primary tool slug. Validated against the registry at resolve time. */
  tool: string;
  /** Optional alternative tool slugs (validated + de-duped against `tool`). */
  related?: string[];
  /** Optional workflow slug to start (validated against discovery). */
  workflow?: string;
  /** Short "why / expert" phrasing that explains the recommendation. */
  note?: string;
}

/* ── Result shapes ────────────────────────────────────────────────────────── */

/** How the assistant arrived at its answer. */
export type IntentType =
  /** Query named a file extension (e.g. "png", "pdf") ⇒ file-type hub. */
  | "file-type"
  /** A curated INTENT_MAP rule matched. */
  | "intent"
  /** Fell back to the fuzzy registry search. */
  | "search"
  /** Nothing matched: empty answer with popular suggestions. */
  | "none";

/** Where a tool runs, surfaced so users know about privacy / upload. */
export type Processing = "Browser" | "Server" | "AI";

/** Rough effort a tool takes, shown as a hint chip. */
export type Difficulty = "Easy" | "Medium";

/** A recommended tool, enriched for display + internal linking. */
export interface ToolRec {
  slug: string;
  title: string;
  /** Category slug. */
  category: string;
  /** Canonical tool route (ROUTES.tool). */
  href: string;
  /** Short, expert reason this tool fits the query. */
  why: string;
  /** Human estimate, e.g. "~10s". */
  estTime: string;
  difficulty: Difficulty;
  /** Where processing happens: Browser (private), Server, or AI model. */
  processing: Processing;
  /** Related tool slugs (validated) for "next step" chips. */
  related: string[];
}

/** A resolved workflow the assistant can start. */
export interface WorkflowRec {
  slug: string;
  title: string;
  href: string;
  steps: { slug: string; title: string; href: string }[];
}

/** A generic internal link (guide / blog / comparison) for SEO cross-linking. */
export interface LinkRec {
  title: string;
  href: string;
  icon: IconName;
  /** One-line context, when available. */
  description?: string;
}

/** The full answer the assistant hands back to the UI. */
export interface AssistantResult {
  /** The original query, trimmed. */
  query: string;
  intentType: IntentType;
  /** SHORT, templated expert sentence. NOT generated by an LLM. */
  answer: string;
  /** The single best tool, when one exists. */
  primary?: ToolRec;
  /** Other good options (validated, de-duped against `primary`). */
  alternatives: ToolRec[];
  /** A guided multi-tool journey, when the intent maps to one. */
  workflow?: WorkflowRec;
  /** Related how-to guides (from lib/content). */
  guides: LinkRec[];
  /** Supporting blog articles (only when blog data is injected, see below). */
  blogs: LinkRec[];
  /** Related "X vs Y" comparisons (from lib/content). */
  comparisons: LinkRec[];
}

/* ── searchEverything (command center) ────────────────────────────────────── */

/** The kind of surface a command-center hit points at. */
export type EverythingKind =
  | "tool"
  | "category"
  | "collection"
  | "workflow"
  | "use-case"
  | "guide"
  | "comparison"
  | "blog"
  | "file-type";

/** One mixed result for the command center, typed with a kind + href + icon. */
export interface EverythingResult {
  kind: EverythingKind;
  title: string;
  description: string;
  href: string;
  icon: IconName;
  /** Lower is better. Lets callers merge/re-sort across sources. */
  score: number;
}

/* ── Optional injected content ────────────────────────────────────────────── */

/**
 * Blog data is filesystem-backed and `server-only` + async, so the engine never
 * imports lib/blog. Instead a server component may pass a pre-computed, slim
 * blog index in when it calls the engine, and blog links are enriched from it.
 * When omitted, `blogs` is simply empty: everything else still works.
 */
export interface AssistantContext {
  /** Slim blog posts (metadata only) to enrich `blogs` / searchEverything. */
  posts?: Pick<BlogPost, "slug" | "title" | "description" | "tool" | "tags" | "category">[];
}
